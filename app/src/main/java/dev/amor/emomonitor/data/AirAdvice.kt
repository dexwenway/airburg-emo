package dev.amor.emomonitor.data

/**
 * 建议必须与 [AirLevel] 的档位一一对应：35/75/115/150/250/350 是同一套阈值，
 * 否则会出现"显示空气正常、建议却说轻度污染"的自相矛盾。
 */
fun adviceFor(pm25: Double): String = when {
    pm25 < 35 -> "空气很干净，开窗通风就好"
    pm25 < 75 -> "空气质量不错，正常通风即可"
    pm25 < 115 -> "轻度污染，关窗并开净化器低档"
    pm25 < 150 -> "中度污染，关闭门窗，净化器中档"
    pm25 < 250 -> "重度污染，尽量留在室内，净化器高档"
    pm25 < 350 -> "严重污染，门窗密封，敏感人群戴口罩"
    else -> "极度污染，建议不要外出"
}
